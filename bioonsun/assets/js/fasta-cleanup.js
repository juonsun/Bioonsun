// BioOnSun — FASTA cleanup tool logic
// All computation happens locally in the browser; no sequence data is ever sent anywhere.
(function () {
  'use strict';

  // ---- Parsing (tolerant of messy / non-standard input) -------------------

  // Splits raw textarea input into records. Blank lines are treated purely as
  // separators and never force a new headerless record on their own, so
  // multi-line-broken pastes with stray empty lines still merge correctly.
  function parseRaw(text) {
    if (!text) return [];
    var lines = text.split(/\r\n|\r|\n/);
    var records = [];
    var current = null;

    lines.forEach(function (line) {
      var trimmed = line.trim();
      if (trimmed.charAt(0) === '>') {
        current = { header: trimmed.slice(1).trim(), bodyLines: [] };
        records.push(current);
        return;
      }
      if (trimmed === '') return; // ignore blank separator lines
      if (!current) {
        current = { header: null, bodyLines: [] };
        records.push(current);
      }
      current.bodyLines.push(line);
    });

    return records;
  }

  function wrap(seq, width) {
    if (!width || seq.length <= width) return seq;
    var out = [];
    for (var i = 0; i < seq.length; i += width) {
      out.push(seq.slice(i, i + width));
    }
    return out.join('\n');
  }

  // Strips everything that isn't a letter (and, optionally, alignment gap
  // "-" characters) from a raw sequence body: whitespace, tabs, digits
  // (common when pasted from a numbered sequence viewer), and stray symbols.
  function cleanSequenceBody(rawBody, keepGaps) {
    var disallowed = keepGaps ? /[^A-Za-z\-]/g : /[^A-Za-z]/g;
    var removedCount = (rawBody.match(disallowed) || []).length;
    var cleaned = rawBody.replace(disallowed, '');
    return { cleaned: cleaned, removedCount: removedCount };
  }

  // ---- Core cleanup pipeline ------------------------------------------

  // options: { keepGaps: bool, caseMode: 'upper'|'lower'|'keep', underscoreHeaders: bool }
  // i18n: { unnamed: string }
  function processInput(text, options, i18n) {
    var rawRecords = parseRaw(text);
    var usedNames = {};
    var results = [];
    var excludedEmpty = 0;

    rawRecords.forEach(function (rec, idx) {
      var rawBody = rec.bodyLines.join('');
      var cleanResult = cleanSequenceBody(rawBody, options.keepGaps);
      var seq = cleanResult.cleaned;
      if (options.caseMode === 'upper') seq = seq.toUpperCase();
      else if (options.caseMode === 'lower') seq = seq.toLowerCase();

      if (seq.length === 0) { excludedEmpty++; return; }

      var headerAutoGenerated = false;
      var name = rec.header ? rec.header.replace(/^>+/, '').trim() : '';
      if (!name) {
        name = i18n.unnamed + '_' + (idx + 1);
        headerAutoGenerated = true;
      }
      if (options.underscoreHeaders) name = name.replace(/\s+/g, '_');

      var duplicateFixed = false;
      var finalName = name;
      if (Object.prototype.hasOwnProperty.call(usedNames, name)) {
        usedNames[name]++;
        finalName = name + '_' + usedNames[name];
        duplicateFixed = true;
      } else {
        usedNames[name] = 1;
      }

      results.push({
        name: finalName,
        seq: seq,
        length: seq.length,
        removedCount: cleanResult.removedCount,
        headerAutoGenerated: headerAutoGenerated,
        duplicateFixed: duplicateFixed
      });
    });

    return { records: results, excludedEmpty: excludedEmpty };
  }

  function buildFasta(records, wrapWidth) {
    return records.map(function (r) {
      return '>' + r.name + '\n' + wrap(r.seq, wrapWidth);
    }).join('\n');
  }

  function escapeHtml(s) {
    return String(s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  // ---- Main init -----------------------------------------------------

  function init(root) {
    var input = root.querySelector('[data-role="input"]');
    var output = root.querySelector('[data-role="output"]');
    var btnSample = root.querySelector('[data-role="sample"]');
    var btnClear = root.querySelector('[data-role="clear"]');
    var wrapWidthSelect = root.querySelector('[data-role="wrap-width"]');
    var caseModeSelect = root.querySelector('[data-role="case-mode"]');
    var keepGapsInput = root.querySelector('[data-role="keep-gaps"]');
    var underscoreHeadersInput = root.querySelector('[data-role="underscore-headers"]');
    var statRecords = root.querySelector('[data-role="stat-records"]');
    var statLength = root.querySelector('[data-role="stat-length"]');
    var statRemoved = root.querySelector('[data-role="stat-removed"]');
    var statAutoHeader = root.querySelector('[data-role="stat-autoheader"]');
    var statDupFix = root.querySelector('[data-role="stat-dupfix"]');
    var statExcluded = root.querySelector('[data-role="stat-excluded"]');
    var tableWrap = root.querySelector('[data-role="table-wrap"]');
    var recordTbody = root.querySelector('[data-role="record-tbody"]');
    var btnCopy = root.querySelector('[data-role="copy"]');
    var btnDownload = root.querySelector('[data-role="download"]');

    var isEn = root.getAttribute('data-i18n') === 'en';
    var i18n = isEn
      ? {
          unnamed: 'sequence',
          copied: 'Copied to clipboard',
          cleared: 'Cleared',
          noInput: 'Paste a sequence first',
          badgeAuto: 'Auto-named',
          badgeDup: 'Duplicate name fixed',
          badgeOk: 'OK'
        }
      : {
          unnamed: '서열',
          copied: '클립보드에 복사했습니다',
          cleared: '초기화했습니다',
          noInput: '먼저 서열을 입력해주세요',
          badgeAuto: '이름 자동 생성',
          badgeDup: '중복 이름 수정됨',
          badgeOk: '정상'
        };

    var sampleSeq = root.getAttribute('data-sample') || '';

    function render() {
      var options = {
        keepGaps: keepGapsInput.checked,
        caseMode: caseModeSelect.value,
        underscoreHeaders: underscoreHeadersInput.checked
      };
      var wrapWidth = parseInt(wrapWidthSelect.value, 10) || 0;
      var result = processInput(input.value, options, i18n);
      var records = result.records;

      var totalLength = 0, totalRemoved = 0, autoHeaderCount = 0, dupFixCount = 0;
      records.forEach(function (r) {
        totalLength += r.length;
        totalRemoved += r.removedCount;
        if (r.headerAutoGenerated) autoHeaderCount++;
        if (r.duplicateFixed) dupFixCount++;
      });

      statRecords.textContent = records.length.toLocaleString();
      statLength.textContent = totalLength.toLocaleString();
      statRemoved.textContent = totalRemoved.toLocaleString();
      statAutoHeader.textContent = autoHeaderCount.toLocaleString();
      statDupFix.textContent = dupFixCount.toLocaleString();
      statExcluded.textContent = result.excludedEmpty.toLocaleString();

      if (records.length === 0) {
        tableWrap.hidden = true;
        recordTbody.innerHTML = '';
        output.value = '';
        return;
      }

      tableWrap.hidden = false;
      recordTbody.innerHTML = records.map(function (r) {
        var badges = '';
        if (r.headerAutoGenerated) badges += '<span class="status-badge warn">' + i18n.badgeAuto + '</span>';
        if (r.duplicateFixed) badges += '<span class="status-badge warn">' + i18n.badgeDup + '</span>';
        if (!r.headerAutoGenerated && !r.duplicateFixed) badges = '<span class="status-badge ok">' + i18n.badgeOk + '</span>';
        return '<tr><td>' + escapeHtml(r.name) + '</td><td>' + r.length.toLocaleString() + '</td><td>' + badges + '</td></tr>';
      }).join('');

      output.value = buildFasta(records, wrapWidth);
    }

    input.addEventListener('input', render);
    wrapWidthSelect.addEventListener('change', render);
    caseModeSelect.addEventListener('change', render);
    keepGapsInput.addEventListener('change', render);
    underscoreHeadersInput.addEventListener('change', render);

    if (btnSample) {
      btnSample.addEventListener('click', function () {
        input.value = sampleSeq;
        render();
      });
    }

    if (btnClear) {
      btnClear.addEventListener('click', function () {
        input.value = '';
        render();
        window.BioOnSun.toast(i18n.cleared);
        input.focus();
      });
    }

    if (btnCopy) {
      btnCopy.addEventListener('click', function () {
        if (!output.value) { window.BioOnSun.toast(i18n.noInput); return; }
        window.BioOnSun.copyText(output.value, i18n.copied);
      });
    }

    if (btnDownload) {
      btnDownload.addEventListener('click', function () {
        if (!output.value) { window.BioOnSun.toast(i18n.noInput); return; }
        window.BioOnSun.download('cleaned.fasta', output.value);
      });
    }

    render();
  }

  document.addEventListener('DOMContentLoaded', function () {
    document.querySelectorAll('[data-tool="fasta-cleanup"]').forEach(init);
  });

  // exposed for potential unit testing
  window.BioOnSunFastaCleanup = {
    parseRaw: parseRaw,
    processInput: processInput,
    buildFasta: buildFasta
  };
})();
